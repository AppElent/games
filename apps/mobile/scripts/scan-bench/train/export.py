"""Writes a trained network as TypeScript: `export.py <net.pt> <digit-net-weights.ts>`.

A layer's weights are stored as bytes: round(weight / scale) + 128.
"""
import base64
import sys

import numpy as np
import torch

state = torch.load(sys.argv[1], map_location="cpu", weights_only=True)
text = "/** The weights of `digit-net.ts`. Generated by `scripts/scan-bench/train/export.py`. */\n"
text += "export const DIGIT_NET_WEIGHTS = [\n"
for name in ("c1", "c2", "c3", "f1", "f2"):
    weight = state[name + ".weight"].flatten().numpy()
    scale = float(np.abs(weight).max() / 127)
    stored = (np.clip(np.round(weight / scale), -127, 127) + 128).astype(np.uint8)
    encoded = base64.b64encode(stored.tobytes()).decode()
    bias = ", ".join(repr(float(f"{b:.5g}")) for b in state[name + ".bias"].numpy())
    text += f'\t{{\n\t\tscale: {float(f"{scale:.6g}")!r},\n\t\tweights:\n\t\t\t"{encoded}",\n\t\tbias: [{bias}],\n\t}},\n'
open(sys.argv[2], "w").write(text + "] as const;\n")
