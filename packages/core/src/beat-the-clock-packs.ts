const PACKS: Record<ClockPackId, Record<Locale, readonly string[]>> = {
	everyday: { en: EVERYDAY_EN, nl: EVERYDAY_NL },
	screen: { en: SCREEN_EN, nl: SCREEN_NL },
	world: { en: WORLD_EN, nl: WORLD_NL },
	kids: { en: KIDS_EN, nl: KIDS_NL },
};

export function isClockPackId(value: string): value is ClockPackId {
	return (CLOCK_PACK_IDS as readonly string[]).includes(value);
}

function packLocale(locale: string): Locale {
	return locale === "nl" ? "nl" : "en";
}

/** A pack's words in a language, deduplicated; the room deals by index into this list. */
export function clockPackWords(packId: string, locale: string) {
	const pack = isClockPackId(packId) ? PACKS[packId] : PACKS.everyday;
	return [...new Set(pack[packLocale(locale)])];
}

/** How many five-word cards a pack has in a language. */
export function clockPackCards(packId: ClockPackId, locale: string) {
	return Math.floor(clockPackWords(packId, locale).length / 5);
}

/** The words at these indices; an index past the pack reads as "". */
export function clockWords(
	packId: string,
	locale: string,
	indices: readonly number[],
) {
	const words = clockPackWords(packId, locale);
	return indices.map((index) => words[index] ?? "");
}
